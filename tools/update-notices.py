#!/usr/bin/env python3
"""Regenerates notices.js from the language files Teams publishes on its CDN.

Run from anywhere with Python 3. Nothing is written unless every step succeeds,
so a change on Microsoft's side cannot leave a partial list behind.
"""
import json
import re
import sys
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

PAGE = "https://teams.microsoft.com/v2/"
ASSETS = "https://teams.public.onecdn.static.microsoft/teams-modular-packages/hashed-assets/"
# The Teams translation key of the notice. If Microsoft renames it, look up the
# new key by searching main-locale-en-us for "may not respond".
KEY = "k6ffnk3uq_mf"
MIN_LANGUAGES = 50
OUTPUT = Path(__file__).resolve().parent.parent / "notices.js"


def fetch(url):
    request = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0 Firefox/140.0"})
    with urllib.request.urlopen(request, timeout=60) as response:
        return response.read().decode("utf-8")


def object_literal(source, name):
    """Returns the "id": "value" pairs of `a.<name>={...}` in the webpack runtime."""
    start = source.index(f"a.{name}={{")
    end = source.index("}", start)
    return dict(re.findall(r'(\d+):"([^"]*)"', source[start:end]))


def locale_urls():
    match = re.search(re.escape(ASSETS) + r"runtime-[0-9a-f]+\.js", fetch(PAGE))
    if not match:
        sys.exit("Could not find the Teams runtime script.")
    runtime = fetch(match.group())
    names, hashes = object_literal(runtime, "un"), object_literal(runtime, "uh")
    return {
        name[len("main-locale-"):]: f"{ASSETS}{name}-{hashes[chunk]}.js"
        for chunk, name in names.items()
        if name.startswith("main-locale-")
    }


def unescape_js(text):
    def replace(match):
        code = match.group(1)
        if code[0] in "xu" and len(code) > 1:
            return chr(int(code[1:].strip("{}"), 16))
        return {"n": "\n", "t": "\t"}.get(code, code)

    return re.sub(r"\\(x[0-9a-fA-F]{2}|u[0-9a-fA-F]{4}|u\{[0-9a-fA-F]+\}|.)", replace, text)


def plural_forms(message):
    """Splits `{membersCount, plural, =1{...} =2{...} other{...}}` into its forms."""
    header = re.match(r"\s*\{\s*membersCount\s*,\s*plural\s*,", message)
    if not header:
        raise ValueError(f"Unexpected message format: {message!r}")
    forms, position = [], header.end()
    selector = re.compile(r"\s*[=\w]+\s*\{")
    while match := selector.match(message, position):
        end, depth = match.end(), 1
        while depth:
            depth += (message[end] == "{") - (message[end] == "}")
            end += 1
        forms.append(message[match.end():end - 1])
        position = end
    return forms


def templates_for(item):
    locale, url = item
    source = fetch(url)
    match = re.search(KEY + r'''\s*:\s*(?:"((?:[^"\\]|\\.)*)"|'((?:[^'\\]|\\.)*)'|`((?:[^`\\]|\\.)*)`)''', source)
    if not match:
        raise ValueError(f"{locale}: key {KEY} not found")
    message = unescape_js(next(group for group in match.groups() if group is not None))
    # '' is how the ICU message format writes a literal apostrophe.
    return locale, [form.replace("''", "'") for form in plural_forms(message)]


def main():
    urls = locale_urls()
    with ThreadPoolExecutor(8) as pool:
        results = dict(pool.map(templates_for, urls.items()))
    if len(results) < MIN_LANGUAGES or "en-us" not in results:
        sys.exit(f"Only found {len(results)} languages; keeping the current notices.js.")
    templates = sorted({form.strip() for forms in results.values() for form in forms})
    OUTPUT.write_text(
        "// Generated by tools/update-notices.py from Microsoft's Teams translations.\n"
        f"// Languages: {' '.join(sorted(results))}\n"
        "var NOTICE_TEMPLATES = "
        + json.dumps(templates, ensure_ascii=False, indent=2)
        + ";\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(templates)} phrases from {len(results)} languages to {OUTPUT}")


if __name__ == "__main__":
    main()
